// scripts/recalcular-horas-presencia.js — Aplica la regla de horas del día (mínimo 8 h si fichó ≥ 6 h; si no
// fichó la salida, 8 h con aviso) a las presencias generadas por el fichaje desde una fecha.
//   node scripts/recalcular-horas-presencia.js 2026-10-01            → simulación
//   node scripts/recalcular-horas-presencia.js 2026-10-01 --aplicar  → lo guarda
const fm = require('../src/fichajeMarcas');
const att = require('../src/attendance');
const { getDB } = require('../src/db');
(async () => {
  const desde = process.argv.find(a => /^\d{4}-\d{2}-\d{2}$/.test(a)) || '2026-10-01';
  const aplicar = process.argv.includes('--aplicar');
  const hoy = fm.fechaHoy();
  const db = await getDB();
  // Días del fichaje: los generados, y los que oficina guardó (p. ej. para poner la obra) con 0 h.
  const ps = (await db.collection('attendance').find({ date: { $gte: desde, $lte: hoy }, autoFromFichaje: true, estado: 'obra', horasManual: { $ne: true } }).sort({ date: 1 }).toArray())
    .filter(a => a.autoGenerated || !(Number(a.horas) > 0));
  for (const a of ps) {
    const e = await fm.estadoActual(a.workerId, a.date);
    const fichadas = Math.round((e.minutos || 0) / 6) / 10;
    let accion;
    if (e.estado !== 'fuera') { if (a.date === hoy) continue; accion = 'sin_salida'; }
    else accion = 'fichadas';
    const nuevo = accion === 'sin_salida' ? { horas: 8, aviso: 'sin_salida' } : att.horasDelDia(fichadas);
    if (nuevo.horas === a.horas && (a.avisoHoras || null) === nuevo.aviso) continue;
    console.log(a.date, (a.workerName || a.workerId).padEnd(18), `antes ${a.horas} h → ${nuevo.horas} h`, `(fichó ${fichadas} h${accion === 'sin_salida' ? ', sin salida' : ''})`, nuevo.aviso || '');
    if (aplicar) { if (accion === 'sin_salida') await att.jornadaSinSalida(a.workerId, a.date); else await att.actualizarHorasFichaje(a.workerId, a.date, fichadas); }
  }
  console.log(aplicar ? 'Aplicado.' : 'Simulación: añade --aplicar.');
  process.exit(0);
})().catch(e => { console.error(e); process.exit(1); });
